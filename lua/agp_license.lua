## From the series (MGM)
- The classic Atlantis event horizon (materials/sgorlin/effect_01, horizon_new_hd): the series' Atlantis horizon.
- The wormhole ride's tunnel (materials/williamdefly/wormhole) and travel sound (sound/stargate/travelnew.mp3): the
  series' wormhole. The ride itself is Ascension Gates' own code (lua/entities/event_horizon/modules/agp_ride.lua).
- The Replicators' walking sound and their quiet call (sound/agp_replicator/rep_walk_loop, rep_chatter2): the series'
  own Replicator sounds - the centre channel of the episodes' 5.1 sound, where the creatures are without the music:
  walking and the quiet, curious call from SG-1 4x01 "Small Victories".
- The Tau'ri soldiers in Ascension Gates' cloth (models/player/agp_cap/cap_soldier_*, materials/models/agp/cap_soldier): ViktorK's SG
  soldier from CAP (body, head, hands, skeleton, textures) rebuilt for Ascension Gates with the cloth recoloured per group. Their shoulder
  patches (patch_l / patch_r) are the series' designs: the Earth patch, the SG-1 team patch and the Atlantis expedition
  patch, their shapes traced from photos of real patches and embroidered anew.
  The women (cap_soldier_*_f1 .. f3) are the same soldier with the head of one of Garry's Mod's own citizens (face,
  hair, eyes: GMod's geometry, GMod's materials referenced, not copied). The Atlantis soldiers' flags (USA, Canada) are
  drawn for Ascension Gates.
- The Goa'uld hand device as worn in third person (models/agp/w_hdevice_fit): the device of CAP's first-person model
  (models/weapons/v_models/v_hdevice: geometry, UVs, materials unchanged) carried joint by joint onto the player
  skeleton's right hand.

